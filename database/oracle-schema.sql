-- Do not run this if these tables already exist or contain data.

CREATE TABLE admin (
    admin_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(100) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    role VARCHAR2(50) DEFAULT 'admin'
);

CREATE TABLE employee (
    emp_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(100) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    phone_no VARCHAR2(20),
    department VARCHAR2(100),
    designation VARCHAR2(100),
    joining_date DATE,
    status VARCHAR2(20) DEFAULT 'Active'
);

CREATE TABLE employee_login (
    login_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id NUMBER NOT NULL,
    username VARCHAR2(100) NOT NULL UNIQUE,
    password VARCHAR2(255) NOT NULL,
    CONSTRAINT employee_login_emp_fk FOREIGN KEY (emp_id) REFERENCES employee(emp_id)
);

CREATE TABLE attendance (
    attendance_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id NUMBER NOT NULL,
    date_col DATE NOT NULL,
    check_in VARCHAR2(10),
    check_out VARCHAR2(10),
    status VARCHAR2(20) DEFAULT 'Present',
    CONSTRAINT attendance_emp_fk FOREIGN KEY (emp_id) REFERENCES employee(emp_id)
);

CREATE TABLE shift (
    shift_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id NUMBER NOT NULL,
    shift_type VARCHAR2(50),
    shift_date DATE NOT NULL,
    start_time VARCHAR2(10),
    end_time VARCHAR2(10),
    CONSTRAINT shift_emp_fk FOREIGN KEY (emp_id) REFERENCES employee(emp_id)
);

CREATE TABLE leave_request (
    leave_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    emp_id NUMBER NOT NULL,
    leave_type VARCHAR2(50) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    reason VARCHAR2(500),
    status VARCHAR2(20) DEFAULT 'Pending',
    CONSTRAINT leave_request_emp_fk FOREIGN KEY (emp_id) REFERENCES employee(emp_id)
);

